// Package merge is the three-way engine that reconciles two PCs' fact stores.
//
// Two rules shape everything in here. The first is that the merge NEVER touches the work
// tree: it is computed out of tree with `merge-tree --write-tree`, resolved in memory,
// committed with `commit-tree`/`update-ref`, and only then materialized file by file.
// The second is that deletion is git's three-way rule and not a union - deleted on one
// side and untouched on the other means DELETED, because the union rule this replaces
// resurrected every deliberate deletion forever and made the judge's migrations
// permanent no-ops.
//
// ASCII-only source (see the store package doc).
package merge

import (
	"bytes"
	"regexp"
)

// reIgnoredLine matches the three frontmatter lines that are NOT content for the purposes
// of the deletion table: `hook:` is regenerated by harvest on whichever PC saw the index
// entry first, `modified:` is a model-written stamp the design declares advisory, and
// `migrated:` is the provenance id harvest stamps from the history's Migrated: trailers
// (decision Q8). A file whose only difference is one of these has not been modified by
// anybody.
//
// `migrated:` joined the list on 2026-09-17: a PC that received the judge's deletions
// under a live session queued them, and its post-merge derive then stamped `migrated:`
// onto every queued file - the id had just arrived in the same merge. The drain compared
// bytes, read the stamp as a session edit, and resurrected all nineteen migrations; the
// next push put three of them back on the hub. Harvest output is never a person's edit.
var reIgnoredLine = regexp.MustCompile(`^\s*(?:hook|modified|migrated)\s*:`)

// Canon is the comparison form of a fact file: CRLF collapsed to LF, and the `hook:`,
// `modified:` and `migrated:` lines dropped.
//
// It is ONLY a comparison form. Nothing is ever written to disk in this shape - writing
// canon() out would delete the very hook the index is rendered from.
func Canon(b []byte) []byte {
	if b == nil {
		return nil
	}
	s := bytes.ReplaceAll(b, []byte("\r\n"), []byte("\n"))
	lines := bytes.Split(s, []byte("\n"))
	kept := lines[:0]
	for _, ln := range lines {
		if reIgnoredLine.Match(ln) {
			continue
		}
		kept = append(kept, ln)
	}
	return bytes.Join(kept, []byte("\n"))
}

// NormalizedEqual reports whether two versions of a fact file say the same thing.
func NormalizedEqual(a, b []byte) bool { return bytes.Equal(Canon(a), Canon(b)) }

// toLF is the WRITE-side normalization: every byte the merge engine writes leaves as LF,
// so a CRLF fact file converges the first time it is merged and never churns again.
func toLF(b []byte) []byte { return bytes.ReplaceAll(b, []byte("\r\n"), []byte("\n")) }
